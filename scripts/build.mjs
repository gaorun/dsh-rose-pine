#!/usr/bin/env node
// Build the browser half: inline the Rosé Pine theme data into lib/client.js.
//
//   src/client.template.js  +  src/tokens.js  ->  lib/client.js
//
// No bundler, no network. The Harness module loader executes lib/client.js
// verbatim, so the template stays readable and the data is injected as one
// `const ROSE_PINE = {...}` literal in place of the `/* @rose-pine-data */` line.

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, relative } from 'node:path'
import { fileURLToPath } from 'node:url'

import { THEMES, PALETTE, tokens } from '../src/tokens.js'

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)))
const TEMPLATE_PATH = join(ROOT, 'src', 'client.template.js')
const OUTPUT_PATH = join(ROOT, 'lib', 'client.js')
const LOCALE_DIR = join(ROOT, 'locale')
const LOCALE_IDS = ['en', 'zh']
const ROW_STRING_KEYS = ['title', 'description', 'darkVariant', 'main', 'moon', 'dawnHint']
const MARKER = '/* @rose-pine-data */'
const BANNER = '// Generated by scripts/build.mjs — do not edit; edit src/ instead.'
const EXPECTED_TOKEN_COUNT = 118

function fail(message) {
  console.error(`build: error: ${message}`)
  process.exit(1)
}

function readTemplate() {
  try {
    return readFileSync(TEMPLATE_PATH, 'utf8')
  } catch (error) {
    fail(`cannot read ${relative(ROOT, TEMPLATE_PATH)} (${error.code ?? error.message})`)
  }
}

/**
 * The settings-row copy lives in locale/*.json so one file holds both the Plugin
 * Manager metadata and the on-screen strings; the browser bundle cannot read
 * files, so the build inlines the `rosePine` section of each locale.
 */
function readStrings() {
  const strings = {}
  for (const id of LOCALE_IDS) {
    const path = join(LOCALE_DIR, `${id}.json`)
    let document
    try {
      document = JSON.parse(readFileSync(path, 'utf8'))
    } catch (error) {
      fail(`cannot read ${relative(ROOT, path)} (${error.code ?? error.message})`)
    }
    const section = document?.rosePine
    if (section === undefined || typeof section !== 'object') {
      fail(`${relative(ROOT, path)} has no "rosePine" object`)
    }
    for (const key of ROW_STRING_KEYS) {
      if (typeof section[key] !== 'string' || section[key].length === 0) {
        fail(`${relative(ROOT, path)} rosePine.${key} is not a non-empty string`)
      }
    }
    strings[id] = Object.fromEntries(ROW_STRING_KEYS.map((key) => [key, section[key]]))
  }
  return strings
}

function buildData() {
  if (!Array.isArray(THEMES) || THEMES.length !== 3) {
    fail(`src/tokens.js must export THEMES with 3 entries, got ${Array.isArray(THEMES) ? THEMES.length : typeof THEMES}`)
  }

  const themes = THEMES.map((theme) => {
    if (!theme || typeof theme.id !== 'string' || typeof theme.variant !== 'string') {
      fail('src/tokens.js THEMES entry is missing id/variant')
    }
    if (!PALETTE || typeof PALETTE[theme.variant] !== 'object') {
      fail(`PALETTE has no entry for variant "${theme.variant}"`)
    }

    const map = tokens(theme.variant)
    if (!map || typeof map !== 'object') {
      fail(`tokens("${theme.variant}") did not return an object`)
    }

    const names = Object.keys(map)
    if (names.length !== EXPECTED_TOKEN_COUNT) {
      fail(`tokens("${theme.variant}") has ${names.length} tokens, expected ${EXPECTED_TOKEN_COUNT}`)
    }
    for (const name of names) {
      if (typeof map[name] !== 'string' || map[name].length === 0) {
        fail(`tokens("${theme.variant}")["${name}"] is not a non-empty string`)
      }
    }

    return { ...theme, tokens: map }
  })

  return { themes, palette: PALETTE, strings: readStrings() }
}

function inject(template, data) {
  const lines = template.split('\n')
  const hits = []
  lines.forEach((line, index) => {
    if (line.trim() === MARKER) hits.push(index)
  })

  if (hits.length !== 1) {
    fail(
      hits.length === 0
        ? `marker "${MARKER}" not found in src/client.template.js`
        : `marker "${MARKER}" found ${hits.length} times in src/client.template.js, expected exactly once`,
    )
  }

  const index = hits[0]
  const indent = lines[index].match(/^[ \t]*/)[0]
  lines[index] = `${indent}const ROSE_PINE = ${JSON.stringify(data, null, 2)};`

  const body = lines.join('\n')
  const output = `${BANNER}\n${body}`
  return output.endsWith('\n') ? output : `${output}\n`
}

const data = buildData()
const output = inject(readTemplate(), data)

mkdirSync(dirname(OUTPUT_PATH), { recursive: true })
writeFileSync(OUTPUT_PATH, output, 'utf8')

const tokenTotal = data.themes.reduce((sum, theme) => sum + Object.keys(theme.tokens).length, 0)
const kib = (Buffer.byteLength(output, 'utf8') / 1024).toFixed(1)
console.log(
  `build: wrote ${relative(ROOT, OUTPUT_PATH)} — ${data.themes.length} themes × ${EXPECTED_TOKEN_COUNT} tokens (${tokenTotal} total), ${kib} KiB`,
)
